const assert = require('assert');
const C = require('../shared/criteria/landscape.json'), T = require('../shared/templates/landscape_ko.json');
const X = require('./landscape-calc.js');
let n = 0; const t = (name, fn) => { fn(); n++; console.log('통과', name); };
t('정비구역 도시지역 3만㎡ 이상 심의 대상', () => assert.strictEqual(X.review(C, { siteArea: 41739 }).dev, '심의 대상'));
t('29,999㎡ 대상 아님', () => assert.strictEqual(X.review(C, { siteArea: 29999 }).dev, '대상 아님'));
t('분양 공동주택 25층 → 시 경관위원회', () => assert.ok(/시 경관위원회/.test(X.review(C, { floors: 25 }).bldWho)));
t('15층·연면적 8만㎡ → 구 경관위원회', () => assert.ok(/구 경관위원회/.test(X.review(C, { floors: 15, gfa: 80000 }).bldWho)));
t('층수 30 / 주변 5 → 6배, 변화 큼', () => assert.strictEqual(X.height(C, { floors: 30, aroundFloors: 5 }).result, '스카이라인 변화 큼'));
t('층수 8 / 주변 5 → 조화', () => assert.strictEqual(X.height(C, { floors: 8, aroundFloors: 5 }).result, '주변과 조화 범위'));
t('배치 없으면 시뮬레이션 보완 필요', () => assert.ok(X.run(C, T, { floors: 30, aroundFloors: 5 }, {}).need[0].includes('개략 배치')));
t('환경성 국가유산 조건 이어받음', () => assert.ok(X.run(C, T, {}, { env: { 국가유산_검토: 'x' } }).list.some(s => /국가유산/.test(s))));
t('조망점 목록', () => assert.deepStrictEqual(X.run(C, T, { views: '숭의역, 수봉공원' }, {}).constraints.조망점, ['숭의역', '수봉공원']));
console.log(`\n${n}개 모두 통과`);
const sq = (x, y, w, d) => [[x, y], [x + w, y], [x + w, y + d], [x, y + d]];
const blds = [{ id: 101, floors: 25, poly: sq(10, 10, 40, 10) }, { id: 102, floors: 25, poly: sq(80, 10, 40, 10) }];
const site = [[0, 0], [200, 0], [200, 100], [0, 100]];
const o = X.openness(blds, site, 0);
console.log('통경축(남북):', o);
assert.strictEqual(o.open, 60); assert.deepStrictEqual(o.gaps, [30, 80]);
const segD = (p, a, b) => { const dx = b[0]-a[0], dy = b[1]-a[1], L = dx*dx+dy*dy; let t = L ? ((p[0]-a[0])*dx+(p[1]-a[1])*dy)/L : 0; t = Math.max(0, Math.min(1, t)); return Math.hypot(p[0]-a[0]-t*dx, p[1]-a[1]-t*dy); };
assert.deepStrictEqual(X.edgeTall(blds, site, 5, 2, 30, segD), [101, 102]);
