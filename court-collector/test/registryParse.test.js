const r = parseRegistry([p1, p2, p4]);

test('머리 정보', () => {
  assert.equal(r.kind, '건물');
  assert.equal(r.uniqueNo, '1716-2003-000646');
  assert.equal(r.address, '경기도 부천시 원미구 가상동 12-3');
  assert.equal(r.viewedAt, '2025.05.09 11:53');
});

test('표제부', () => {
  assert.equal(r.sections.pyo.length, 1);
  assert.match(Object.values(r.sections.pyo[0]).join(' '), /85\.33㎡/);
});

test('갑구: 쪽을 넘어 이어지는 기록, 칸 나누기, 말소', () => {
  const g = r.sections.gap;
  assert.deepEqual(g.map((x) => x.rank), ['1', '2', '3', '4', '5']);
  assert.equal(g[1].purpose, '소유권이전');
  assert.equal(g[1].date, '2010.03.02');
  assert.equal(g[1].receiptNo, '2000');
  assert.match(g[1].holder, /이가상/);
  assert.doesNotMatch(g[1].holder, /640510/, '주민번호 앞자리는 지움');
  assert.equal(g[2].purpose, '2번이가상지분가압류');
  assert.equal(g[2].amount, 10000000);
  assert.doesNotMatch(g[2].holder, /110111/, '법인번호도 지움');
  assert.equal(g[3].purpose, '2번이가상지분강제경매개시결정');
  assert.match(g[3].cause, /정\(2024타경571\)/);
  assert.equal(g[2].canceled, true, '5번 말소 기록이 3번 가압류를 지움');
  assert.equal(g[4].cancelEntry, true);
});

test('을구: 부기등기와 말소', () => {
  const e = r.sections.eul;
  assert.deepEqual(e.map((x) => x.rank), ['1', '1-1', '2', '3']);
  assert.equal(e[0].amount, 39000000);
  assert.equal(e[0].canceled, true);
  assert.equal(e[1].canceled, true, '주등기가 말소되면 부기도 말소');
  assert.equal(e[2].purpose, '1번근저당권설정등기말소');
  assert.equal(e[3].canceled, undefined);
});

test('주요 등기사항 요약(살아 있는 권리)', () => {
  assert.equal(r.summary.owners.length, 2);
  assert.match(r.summary.owners[0].name, /이가상/);
  assert.equal(r.summary.owners[0].share, '2분의 1');
  assert.equal(r.summary.owners[0].rank, '2');
  assert.match(r.summary.owners[0].address, /부천시/);
  assert.equal(r.summary.gap.length, 1);
  assert.equal(r.summary.gap[0].purpose, '강제경매개시결정');
  assert.equal(r.summary.gap[0].rank, '4');
  assert.equal(r.summary.eul.length, 1);
  assert.equal(r.summary.eul[0].amount, 50000000);
});

test('분석 표시: 말소기준권리보다 앞선 전세권은 인수 위험', () => {
  assert.equal(r.flags.baseRight.purpose, '강제경매개시결정');
  assert.equal(r.flags.baseRight.date, '2024.06.21');
  assert.deepEqual(r.flags.senior, [{ purpose: '전세권설정', date: '2018.02.01' }]);
  assert.equal(r.flags.lease, 1);
  assert.equal(r.flags.owners, 2);
  assert.equal(r.flags.shareOwners, true);
  assert.equal(r.flags.attachment, undefined, '말소된 가압류는 셈하지 않음');
});

test('전체 글자에는 등록번호가 없음', () => {
  const t = plainText([p1, p2, p4]);
  assert.match(t, /소유권보존/);
  assert.doesNotMatch(t, /\d{6}-[\d*]{7}/);
  assert.doesNotMatch(t, /MYAUCTION|M Y A U C T I O N/);
});
